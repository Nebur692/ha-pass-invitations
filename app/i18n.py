"""Minimal i18n: Accept-Language detection + string tables.

Two independent audiences, two detection strategies, two different
language sets:
  - Guest PWA: always auto-detected from the guest's own browser
    (Accept-Language). No override — a guest link isn't "owned" by anyone
    who'd have a profile to configure. Translated into all 24 official
    languages of the European Union, since a guest link can end up in
    anyone's hands.
  - Admin dashboard: auto-detected by default, but overridable via a
    persisted cookie set from the admin's own Profile section (see
    app/routers/admin.py `/admin/profile/language`). Stays EN/ES only —
    it's the household's own dashboard, not guest-facing.

No pluralization engine, no .po files — just flat dicts per audience.
"""
from fastapi import Request

# The 24 official languages of the European Union (ISO 639-1).
GUEST_SUPPORTED_LANGS = (
    "bg", "hr", "cs", "da", "nl", "en", "et", "fi", "fr", "de", "el", "hu",
    "ga", "it", "lv", "lt", "mt", "pl", "pt", "ro", "sk", "sl", "es", "sv",
)
ADMIN_SUPPORTED_LANGS = ("en", "es")
# Kept as a general-purpose default (e.g. for direct detect_lang() calls
# that don't care which audience) — the guest set is the superset of the two.
SUPPORTED_LANGS = GUEST_SUPPORTED_LANGS
DEFAULT_LANG = "en"

ADMIN_LANG_COOKIE = "hp_admin_lang"


def _parse_accept_language(header: str) -> list[str]:
    tags: list[tuple[str, float]] = []
    for part in header.split(","):
        part = part.strip()
        if not part:
            continue
        if ";q=" in part:
            tag, q = part.split(";q=", 1)
            try:
                weight = float(q)
            except ValueError:
                weight = 1.0
        else:
            tag, weight = part, 1.0
        tags.append((tag.strip().lower(), weight))
    tags.sort(key=lambda x: x[1], reverse=True)
    return [t for t, _ in tags]


def detect_lang(accept_language: str | None, langs: tuple[str, ...] = SUPPORTED_LANGS) -> str:
    if not accept_language:
        return DEFAULT_LANG
    for tag in _parse_accept_language(accept_language):
        primary = tag.split("-")[0]
        if primary in langs:
            return primary
    return DEFAULT_LANG


def get_guest_lang(request: Request) -> str:
    return detect_lang(request.headers.get("accept-language"), GUEST_SUPPORTED_LANGS)


def get_admin_lang(request: Request) -> str:
    cookie_val = request.cookies.get(ADMIN_LANG_COOKIE)
    if cookie_val in ADMIN_SUPPORTED_LANGS:
        return cookie_val
    return detect_lang(request.headers.get("accept-language"), ADMIN_SUPPORTED_LANGS)


def is_admin_lang_auto(request: Request) -> bool:
    return request.cookies.get(ADMIN_LANG_COOKIE) not in ADMIN_SUPPORTED_LANGS


def make_t(strings: dict[str, dict[str, str]], lang: str):
    """Returns a t(key, **kwargs) callable bound to the resolved language.

    Falls back to English for any key missing in a non-English table, then
    to the raw key itself if truly missing everywhere (so a typo shows up
    as an ugly-but-visible key rather than a blank string).
    """
    table = strings.get(lang, strings[DEFAULT_LANG])
    fallback = strings[DEFAULT_LANG]

    def t(key: str, **kwargs) -> str:
        text = table.get(key, fallback.get(key, key))
        for k, v in kwargs.items():
            text = text.replace("{" + k + "}", str(v))
        return text

    return t


